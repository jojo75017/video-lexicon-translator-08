function buildNiches(): Niche600[] {
  const out: Niche600[] = [];
  let id = 1;
  for (const cat of niches600Categories) {
    const templates = TEMPLATES[cat.key] || [];
    for (let i = 0; i < templates.length; i++) {
      const t = templates[i];
      // formule déterministe (pas de Math.random)
      const bsr = 2000 + ((i * 137) % 28000);
      const concIdx = (i * 3) % 3;
      const concurrence = (['Faible', 'Modérée', 'Élevée'] as const)[concIdx];
      const potentiel = (5 - concIdx + (i % 2)) as 1 | 2 | 3 | 4 | 5;
      const prix = 2.99 + ((i % 7) * 0.5);
      out.push({
        id: id++,
        niche: t.sub,
        sousNiche: cat.label,
        motCleAmazon: t.kw,
        bsrCible: bsr,
        concurrence,
        potentiel: Math.min(5, Math.max(1, potentiel)) as 1 | 2 | 3 | 4 | 5,
        exemplePrix: Math.round(prix * 100) / 100,
        category: cat.key,
        emoji: cat.emoji,
      });
    }
  }
  return out;
}

